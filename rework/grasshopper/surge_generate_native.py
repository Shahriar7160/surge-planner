"""S.U.R.G.E. — run the ward generator INSIDE Grasshopper (Rhino 8 Python 3 component, no server).

Component inputs (right-click each input → Type hint):
    repo    : str    full path to the 'rework' folder, e.g. C:\\Users\\you\\Big-Data\\rework
    site    : str    S1, S2, S3 or S4
    per_row : int    max ward modules per row (slider 2–8)
    bay     : float  structural bay in metres (slider 4.8–7.2)
    tent    : bool   True = folded tents, False = boxes
Component outputs:
    geo, colour, name, zone, checks
Plug geo + colour into a Custom Preview. Move the sliders: the layout is regenerated by the same code as
pipeline/s4_layout.py, so the Python pipeline and Grasshopper never drift apart.
"""
import importlib
import json
import os
import sys

import Rhino.Geometry as rg
import System.Drawing as sd


# ---- check the component's inputs (names must match exactly) ----
_missing = [n for n in ["repo", "site"] if n not in globals() or globals()[n] is None]
if _missing:
    raise ValueError("Missing input(s): " + ", ".join(_missing) +
                     ". Zoom in on the component, right-click each input and rename it exactly: repo = full path to the rework folder, site = S1..S4, per_row = int, bay = float, tent = True/False")

per_row = globals().get("per_row") or 5    # optional inputs
bay = globals().get("bay") or 6.0
tent = globals().get("tent", True)

pipeline = os.path.join(repo, "pipeline")
if pipeline not in sys.path:
    sys.path.insert(0, pipeline)
if not os.path.exists(os.path.join(pipeline, "s4_layout.py")):
    raise ValueError("Can't find " + os.path.join(pipeline, "s4_layout.py") + ". 'repo' must be the rework folder "
                     "(the one containing pipeline, data and grasshopper). If it is in OneDrive, make sure the files "
                     "are downloaded: right-click the folder → Always keep on this device.")
import s4_params  # noqa: E402
import s4_layout  # noqa: E402

importlib.reload(s4_params)
s4_params.MAX_MODULES_PER_ROW = int(per_row) if per_row else 5
s4_params.BAY = float(bay) if bay else 6.0
importlib.reload(s4_layout)

briefs = json.load(open(os.path.join(repo, "data", "s3", "briefs.json"), encoding="utf-8"))["sites"]
brief = next(b for b in briefs if b["site_id"] == (site or "S1"))
L = s4_layout.layout(brief)
checks = json.dumps(s4_layout.check(L, brief), indent=1)

COL = {"red": sd.Color.FromArgb(227, 73, 72), "amber": sd.Color.FromArgb(237, 161, 0),
       "green": sd.Color.FromArgb(27, 175, 122), "service": sd.Color.FromArgb(138, 136, 127)}
WARD = {"suspect": sd.Color.FromArgb(246, 185, 178), "probable": sd.Color.FromArgb(238, 139, 129),
        "confirmed": sd.Color.FromArgb(184, 48, 47)}
E, K, H = s4_params.MODULE_H, s4_params.MODULE_RIDGE, s4_params.SERVICE_H

geo, colour, name, zone = [], [], [], []
for r in L["rects"]:
    if r["name"] in ("staff_dormitory", "burial_area"):
        continue
    x, y, w, d = r["x"], r["y"], r["w"], r["h"]
    if r["kind"] == "ward_module" and tent:
        prof = rg.PolylineCurve([rg.Point3d(x, y, 0), rg.Point3d(x, y, E), rg.Point3d(x + w / 2, y, K),
                                 rg.Point3d(x + w, y, E), rg.Point3d(x + w, y, 0), rg.Point3d(x, y, 0)])
        b = rg.Surface.CreateExtrusion(prof, rg.Vector3d(0, d, 0)).ToBrep().CapPlanarHoles(0.001)
    else:
        h = 0.2 if r["kind"] == "corridor" else (E if r["kind"] == "ward_module" else H)
        b = rg.Box(rg.BoundingBox(rg.Point3d(x, y, 0), rg.Point3d(x + w, y + d, h))).ToBrep()
    if b is None:                      # Rhino could not build this solid; skip it
        print("skipped (no geometry):", r["name"])
        continue
    geo.append(b)
    colour.append(WARD.get(r.get("ward"), COL[r["zone"]]) if r["kind"] == "ward_module" else COL[r["zone"]])
    name.append(r["name"])
    zone.append(r["zone"])

print("S.U.R.G.E.: site", site, "→", len(geo), "solids in 'geo'. If 'geo' looks empty, the OUTPUT must be named exactly geo "
      "(and colour, name, zone).")
